import { NextResponse } from "next/server";
import { getAuthSession, comparePassword } from "@/lib/auth";
import { db } from "@/lib/db";
import {
  generateTotpSecret,
  generateTotpUri,
  verifyTotpCode,
  generateBackupCodes,
  hashBackupCode,
  verifyBackupCode,
} from "@/lib/totp";
import { encryptTwoFactorSecret, decryptTwoFactorSecret } from "@/lib/two-factor-cipher";
import { checkRateLimit } from "@/lib/rate-limit";
import { getClientIp } from "@/lib/ip";
import { z } from "zod";

const verify2faSchema = z.object({
  password: z.string().min(1, "Password is required to enable 2FA"),
  code: z.string().min(6).max(9),
  currentCode: z.string().optional(),
  secret: z.string().optional(),
});

const disable2faSchema = z.object({
  password: z.string().min(1, "Password is required to disable 2FA"),
  code: z.string().optional(),
});

export async function GET(req: Request) {
  try {
    const ip = getClientIp(req);
    if (!(await checkRateLimit(ip + "_2fa_get"))) {
      return NextResponse.json({ error: "Too many requests" }, { status: 429 });
    }

    const session = await getAuthSession(req);
    if (!session) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const user = await db.platformUser.findUnique({
      where: { id: session.user.id },
      select: { id: true, email: true, twoFactorEnabled: true },
    });

    if (!user) {
      return NextResponse.json({ error: "User not found" }, { status: 404 });
    }

    const { searchParams } = new URL(req.url);
    const action = searchParams.get("action");

    if (action === "setup") {
      if (user.twoFactorEnabled) {
        return NextResponse.json({
          enabled: true,
          message: "2FA is already enabled on this account",
        });
      }

      const secret = generateTotpSecret(20);
      const uri = generateTotpUri(user.email, secret, "e-darschi");

      // Store pending secret encrypted on server until confirmed with code & password
      await db.platformUser.update({
        where: { id: user.id },
        data: {
          twoFactorPendingSecret: encryptTwoFactorSecret(secret),
        },
      });

      return NextResponse.json({
        enabled: false,
        secret,
        uri,
      });
    }

    return NextResponse.json({
      enabled: Boolean(user.twoFactorEnabled),
    });
  } catch (err: unknown) {
    console.error("[GET /api/auth/2fa]", err);
    return NextResponse.json({ error: "Internal server error" }, { status: 500 });
  }
}

export async function POST(req: Request) {
  try {
    const ip = getClientIp(req);
    if (!(await checkRateLimit(ip + "_2fa_post"))) {
      return NextResponse.json({ error: "Too many requests" }, { status: 429 });
    }

    const session = await getAuthSession(req);
    if (!session) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await req.json();
    const parsed = verify2faSchema.safeParse(body);
    if (!parsed.success) {
      const fieldErrors = parsed.error.flatten().fieldErrors;
      let errorMsg = "Validation error";
      if (fieldErrors.password) {
        errorMsg = "Password is required to enable 2FA";
      } else if (fieldErrors.code) {
        errorMsg = "Invalid TOTP verification code";
      }
      return NextResponse.json(
        { error: errorMsg, details: parsed.error.format() },
        { status: 400 }
      );
    }

    const { password, code, currentCode, secret: clientSecret } = parsed.data;

    const user = await db.platformUser.findUnique({
      where: { id: session.user.id },
      select: {
        id: true,
        passwordHash: true,
        twoFactorEnabled: true,
        twoFactorSecret: true,
        twoFactorPendingSecret: true,
      },
    });

    if (!user) {
      return NextResponse.json({ error: "User not found" }, { status: 404 });
    }

    // 1. Password verification is mandatory
    const isPasswordValid = await comparePassword(password, user.passwordHash);
    if (!isPasswordValid) {
      return NextResponse.json({ error: "Invalid current password" }, { status: 403 });
    }

    // 2. If 2FA already enabled, require current 2FA code to reconfigure
    if (user.twoFactorEnabled && user.twoFactorSecret) {
      if (!currentCode) {
        return NextResponse.json(
          { error: "Current 2FA code is required to reconfigure 2FA" },
          { status: 400 }
        );
      }
      const existingDecryptedSecret = decryptTwoFactorSecret(user.twoFactorSecret);
      const isCurrentValid = verifyTotpCode(existingDecryptedSecret, currentCode);
      if (!isCurrentValid) {
        return NextResponse.json({ error: "Invalid current 2FA code" }, { status: 400 });
      }
    }

    // 3. Resolve the secret to activate: pending secret generated by server or client secret fallback
    let candidateSecret = "";
    if (user.twoFactorPendingSecret) {
      candidateSecret = decryptTwoFactorSecret(user.twoFactorPendingSecret);
    } else if (clientSecret) {
      candidateSecret = clientSecret;
    }

    if (!candidateSecret) {
      return NextResponse.json(
        { error: "No pending 2FA setup found. Please initialize setup first." },
        { status: 400 }
      );
    }

    const isValid = verifyTotpCode(candidateSecret, code);
    if (!isValid) {
      return NextResponse.json(
        { error: "Invalid TOTP verification code" },
        { status: 400 }
      );
    }

    // 4. Generate 10 single-use cryptographic backup codes and store only their SHA-256 hashes
    const backupCodes = generateBackupCodes(10);
    const backupHashes = backupCodes.map(hashBackupCode);

    // 5. Store AES-256-GCM encrypted secret and backup hashes in database
    await db.platformUser.update({
      where: { id: session.user.id },
      data: {
        twoFactorEnabled: true,
        twoFactorSecret: encryptTwoFactorSecret(candidateSecret),
        twoFactorPendingSecret: null,
        twoFactorBackupCodes: JSON.stringify(backupHashes),
      },
    });

    await db.auditLog.create({
      data: {
        actorUserId: session.user.id,
        action: "2FA_ENABLED",
        resource: "PlatformUser",
        resourceId: session.user.id,
        detailsJson: JSON.stringify({ method: "TOTP" }),
        ipAddress: ip,
      },
    });

    return NextResponse.json({
      success: true,
      enabled: true,
      backupCodes,
      message: "Two-factor authentication successfully enabled",
    });
  } catch (err: unknown) {
    console.error("[POST /api/auth/2fa]", err);
    return NextResponse.json({ error: "Internal server error" }, { status: 500 });
  }
}

export async function DELETE(req: Request) {
  try {
    const ip = getClientIp(req);
    if (!(await checkRateLimit(ip + "_2fa_delete"))) {
      return NextResponse.json({ error: "Too many requests" }, { status: 429 });
    }

    const session = await getAuthSession(req);
    if (!session) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await req.json();
    const parsed = disable2faSchema.safeParse(body);
    if (!parsed.success) {
      return NextResponse.json(
        { error: "Password is required to disable 2FA" },
        { status: 400 }
      );
    }

    const user = await db.platformUser.findUnique({
      where: { id: session.user.id },
    });

    if (!user) {
      return NextResponse.json({ error: "User not found" }, { status: 404 });
    }

    const isMatch = await comparePassword(parsed.data.password, user.passwordHash);
    if (!isMatch) {
      return NextResponse.json({ error: "Invalid password" }, { status: 403 });
    }

    // If 2FA code is provided, verify it (TOTP or backup code)
    if (parsed.data.code && user.twoFactorSecret) {
      const decryptedSecret = decryptTwoFactorSecret(user.twoFactorSecret);
      const isTotp = verifyTotpCode(decryptedSecret, parsed.data.code);
      const isBackup = verifyBackupCode(parsed.data.code, user.twoFactorBackupCodes).valid;
      if (!isTotp && !isBackup) {
        return NextResponse.json({ error: "Invalid 2FA code" }, { status: 400 });
      }
    }

    await db.platformUser.update({
      where: { id: user.id },
      data: {
        twoFactorEnabled: false,
        twoFactorSecret: null,
        twoFactorPendingSecret: null,
        twoFactorBackupCodes: null,
        twoFactorLastStep: null,
      },
    });

    await db.auditLog.create({
      data: {
        actorUserId: user.id,
        action: "2FA_DISABLED",
        resource: "PlatformUser",
        resourceId: user.id,
        detailsJson: JSON.stringify({ reason: "User requested" }),
        ipAddress: ip,
      },
    });

    return NextResponse.json({
      success: true,
      enabled: false,
      message: "Two-factor authentication disabled",
    });
  } catch (err: unknown) {
    console.error("[DELETE /api/auth/2fa]", err);
    return NextResponse.json({ error: "Internal server error" }, { status: 500 });
  }
}
